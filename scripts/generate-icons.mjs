// Writes the Lucide icons the app uses to src/lib/icons.ts so the browser never calls the Iconify API.
import fs from 'node:fs';
import { icons } from '@iconify-json/lucide';

const NAMES = [
	'search',
	'settings',
	'log-out',
	'refresh-cw',
	'plug-zap',
	'trash-2',
	'external-link',
	'film',
	'tv',
	'plus',
	'circle-alert',
	'circle-check',
	'arrow-left',
	'power',
	'library',
	'star',
	'scan-barcode',
	'camera',
	'camera-off'
];

const width = icons.width ?? 24;
const height = icons.height ?? 24;
const entries = NAMES.map((name) => {
	const icon = icons.icons[name] ?? icons.icons[icons.aliases?.[name]?.parent];
	if (!icon) throw new Error(`Unknown Lucide icon: ${name}`);
	return `\t'${name}': { width: ${width}, height: ${height}, body: ${JSON.stringify(icon.body)} }`;
});

fs.writeFileSync(
	new URL('../src/lib/icons.ts', import.meta.url),
	`// Generated by scripts/generate-icons.mjs. Do not edit by hand.\nimport type { IconifyIcon } from '@iconify/svelte';\n\nexport const icons = {\n${entries.join(',\n')}\n} satisfies Record<string, IconifyIcon>;\n\nexport type IconName = keyof typeof icons;\n`
);
